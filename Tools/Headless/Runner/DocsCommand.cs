    /// <summary>
    /// The "docs" command: writes the docs that are derived from the live model, so they cannot
    /// drift from it. PARAMETERS.md reflects over SimTuning; SOCIETY_GRAPH.md is built from every
    /// term the ledger records while the built-in lever scripts play out.
    /// </summary>
    internal static class DocsCommand
    {
        const string Banner = "<!-- GENERATED by Tools/Headless/Runner (docs command). Do not edit by hand: change the code, then regenerate. -->";
        const int GraphYears = 60;

        static readonly HashSet<string> PerVicePrefixes = new HashSet<string>
        {
            "Media", "Mood", "Disposition", "Expressed", "Channels", "Outlet", "Frustration", "Alignment", "Schooling",
        };

        public static int Execute(Options options)
        {
            string outDir = options.Get("out", null) ?? Path.Combine(Options.FindRepoRoot(), "Docs", "generated");
            Directory.CreateDirectory(outDir);

            WriteDoc(Path.Combine(outDir, "PARAMETERS.md"), ParametersDoc(XmlDocs.Load()));
            WriteDoc(Path.Combine(outDir, "SOCIETY_GRAPH.md"), GraphDoc());
            Console.WriteLine($"Wrote PARAMETERS.md and SOCIETY_GRAPH.md to {outDir}");
            return 0;
        }

        static void WriteDoc(string path, string content) =>
            File.WriteAllText(path, content.Replace("\r\n", "\n"), new UTF8Encoding(false));

        // ---- PARAMETERS.md ------------------------------------------------------------------

        static string ParametersDoc(XmlDocs docs)
        {
            var doc = new StringBuilder();
            doc.AppendLine(Banner);
            doc.AppendLine("# Model parameters");
            doc.AppendLine();
            doc.AppendLine("Live default value of every coefficient in `SimTuning` (Assets/Scripts/Sim/Tuning), with the meaning");
            doc.AppendLine("from each field's XML summary. All values are provisional until a balance pass. To change one, edit the");
            doc.AppendLine("field initializer and regenerate: `dotnet run --project Tools/Headless/Runner -- docs`.");

            var tuning = SimTuning.CreateDefault();
            foreach (var section in PublicFields(typeof(SimTuning)))
            {
                object sectionValue = section.GetValue(tuning);
                Type sectionType = section.FieldType;
                doc.AppendLine();
                doc.AppendLine($"## {section.Name} (`{sectionType.Name}`)");
                string sectionSummary = docs.Summary(sectionType);
                if (sectionSummary.Length > 0) doc.AppendLine().AppendLine(sectionSummary);
                doc.AppendLine();
                doc.AppendLine("| Parameter | Value | Meaning |");
                doc.AppendLine("|---|---|---|");

                var matrices = new List<(FieldInfo Field, ViceVector[] Rows)>();
                var traitTables = new List<(FieldInfo Field, GovernmentTraits[] Types)>();
                var terrainTables = new List<(FieldInfo Field, double[][] Rows)>();
                // Three-entry arrays are per cohort, except in the economy, where they are per resource.
                bool perResource = sectionType == typeof(EconomyTuning);
                foreach (var field in PublicFields(sectionType))
                {
                    object value = field.GetValue(sectionValue);
                    string meaning = Cell(docs.Summary(field));
                    if (value is ViceVector[] rows)
                    {
                        doc.AppendLine($"| {field.Name} | table below | {meaning} |");
                        matrices.Add((field, rows));
                    }
                    else if (value is double[][] terrainRows)
                    {
                        doc.AppendLine($"| {field.Name} | table below | {meaning} |");
                        terrainTables.Add((field, terrainRows));
                    }
                    else if (value is GovernmentTraits[] types)
                    {
                        doc.AppendLine($"| {field.Name} | table below | {meaning} |");
                        traitTables.Add((field, types));
                    }
                    else
                    {
                        doc.AppendLine($"| {field.Name} | {Cell(Format(value, perResource))} | {meaning} |");
                    }
                }

                foreach (var (field, rows) in matrices)
                {
                    doc.AppendLine();
                    doc.AppendLine($"**{field.Name}**");
                    doc.AppendLine();
                    doc.Append("| Row |");
                    for (int v = 0; v < ViceVector.Count; v++) doc.Append(' ').Append((Vice)v).Append(" |");
                    doc.AppendLine();
                    doc.Append("|---|");
                    for (int v = 0; v < ViceVector.Count; v++) doc.Append("---|");
                    doc.AppendLine();
                    for (int r = 0; r < rows.Length; r++)
                    {
                        string label = rows.Length == Curriculum.FocusCount ? ((CurriculumFocus)r).ToString() : r.ToString(CultureInfo.InvariantCulture);
                        doc.Append("| ").Append(label).Append(" |");
                        for (int v = 0; v < ViceVector.Count; v++) doc.Append(' ').Append(Number(rows[r][v])).Append(" |");
                        doc.AppendLine();
                    }
                }

                foreach (var (field, rows) in terrainTables)
                {
                    doc.AppendLine();
                    doc.AppendLine($"**{field.Name}** (one row per Terrain, one column per Resource)");
                    doc.AppendLine();
                    doc.Append("| Terrain |");
                    for (int r = 0; r < EconomyState.ResourceCount; r++) doc.Append(' ').Append((Resource)r).Append(" |");
                    doc.AppendLine();
                    doc.Append("|---|");
                    for (int r = 0; r < EconomyState.ResourceCount; r++) doc.Append("---|");
                    doc.AppendLine();
                    for (int t = 0; t < rows.Length; t++)
                    {
                        doc.Append("| ").Append((Terrain)t).Append(" |");
                        for (int r = 0; r < rows[t].Length; r++) doc.Append(' ').Append(Number(rows[t][r])).Append(" |");
                        doc.AppendLine();
                    }
                }

                foreach (var (field, types) in traitTables)
                {
                    doc.AppendLine();
                    doc.AppendLine($"**{field.Name}** (one column per GovernmentType; meanings in the GovernmentTraits table below)");
                    doc.AppendLine();
                    doc.Append("| Trait |");
                    for (int k = 0; k < types.Length; k++) doc.Append(' ').Append((GovernmentType)k).Append(" |");
                    doc.AppendLine();
                    doc.Append("|---|");
                    for (int k = 0; k < types.Length; k++) doc.Append("---|");
                    doc.AppendLine();
                    foreach (var trait in PublicFields(typeof(GovernmentTraits)))
                    {
                        doc.Append("| ").Append(trait.Name).Append(" |");
                        foreach (var type in types) doc.Append(' ').Append(Cell(Compact(trait.GetValue(type)))).Append(" |");
                        doc.AppendLine();
                    }
                    doc.AppendLine();
                    doc.AppendLine("| GovernmentTraits field | Meaning |");
                    doc.AppendLine("|---|---|");
                    foreach (var trait in PublicFields(typeof(GovernmentTraits)))
                        doc.AppendLine($"| {trait.Name} | {Cell(docs.Summary(trait))} |");
                }
            }
            return doc.ToString();
        }

        // Nonzero entries only, so a five-column table stays readable.
        static string Compact(object value)
        {
            switch (value)
            {
                case ViceVector v:
                    var vices = new List<string>();
                    for (int i = 0; i < ViceVector.Count; i++)
                        if (v[i] != 0) vices.Add($"{(Vice)i} {Number(v[i])}");
                    return vices.Count == 0 ? "-" : string.Join(", ", vices);
                case double[] focuses when focuses.Length == Curriculum.FocusCount:
                    var parts = new List<string>();
                    for (int i = 0; i < focuses.Length; i++)
                        if (focuses[i] != 0) parts.Add($"{(CurriculumFocus)i} {Number(focuses[i])}");
                    return parts.Count == 0 ? "-" : string.Join(", ", parts);
                default:
                    return Format(value);
            }
        }

        static IEnumerable<FieldInfo> PublicFields(Type type) =>
            type.GetFields(BindingFlags.Public | BindingFlags.Instance).OrderBy(f => f.MetadataToken);

        static string Format(object value, bool perResource = false)
        {
            switch (value)
            {
                case double d:
                    return Number(d);
                case ViceVector v:
                    var parts = new string[ViceVector.Count];
                    for (int i = 0; i < ViceVector.Count; i++) parts[i] = $"{(Vice)i} {Number(v[i])}";
                    return string.Join(", ", parts);
                case double[] values:
                    var labels = values.Length != 3 ? null
                        : perResource ? new[] { "Food", "Materials", "Luxuries" } : new[] { "Youth", "Adult", "Elder" };
                    var items = new string[values.Length];
                    for (int i = 0; i < values.Length; i++)
                        items[i] = labels != null ? $"{labels[i]} {Number(values[i])}" : Number(values[i]);
                    return string.Join(", ", items);
                case bool flag:
                    return flag ? "yes" : "no";
                default:
                    return value == null ? "null" : value.ToString();
            }
        }

        static string Number(double value) => value.ToString("0.####", CultureInfo.InvariantCulture);

        static string Cell(string text) => text.Replace("|", "\\|");

        // ---- SOCIETY_GRAPH.md ---------------------------------------------------------------

        /// <summary>Running statistics for one source-to-target edge across every run.</summary>
        sealed class EdgeStats
        {
            public double SumAbs;
            public long Count;
            public bool Positive;
            public bool Negative;

            public double Typical => Count == 0 ? 0 : SumAbs / Count;

            public string Sign => Positive && Negative ? "+/-" : (Negative ? "-" : "+");

            public void Add(double amount)
            {
                SumAbs += Math.Abs(amount);
                Count++;
                if (amount > 0) Positive = true;
                if (amount < 0) Negative = true;
            }

            public void Merge(EdgeStats other)
            {
                SumAbs += other.SumAbs;
                Count += other.Count;
                Positive |= other.Positive;
                Negative |= other.Negative;
            }
        }

        static string GraphDoc()
        {
            var edges = new Dictionary<(string Source, string Target), EdgeStats>();
            string[] scripts = LeverScripts.Names();
            foreach (string script in scripts)
            {
                LeverScripts.TryGet(script, out var onYearStart, out _);
                var simulation = new Simulation(ScenarioLibrary.ThreeNations(), SimTuning.CreateDefault(), 1);
                int home = simulation.World.PlayerHomeIndex;
                for (int year = 1; year <= GraphYears; year++)
                {
                    onYearStart(simulation, simulation.Date.Year, home);
                    for (int month = 0; month < SimDate.MonthsPerYear; month++)
                    {
                        simulation.Advance();
                        foreach (var term in simulation.Ledger.Entries)
                        {
                            var key = (term.Source, term.TargetName);
                            if (!edges.TryGetValue(key, out var stats)) edges[key] = stats = new EdgeStats();
                            stats.Add(term.Amount);
                        }
                    }
                }
            }

            var doc = new StringBuilder();
            doc.AppendLine(Banner);
            doc.AppendLine("# Society causal graph");
            doc.AppendLine();
            doc.AppendLine("What feeds what in the society model, observed from the ledger rather than declared: every term the");
            doc.AppendLine($"simulation recorded while the three-nation scenario ran each built-in lever script for {GraphYears} years");
            doc.AppendLine($"({string.Join(", ", scripts)}). Solid arrows are observed terms; dotted arrows are slow stock dynamics");
            doc.AppendLine("that the ledger does not record (declared in Tools/Headless/Runner/DocsCommand.cs). The model itself is");
            doc.AppendLine("explained in Docs/simulation/MODEL.md.");
            doc.AppendLine();
            doc.AppendLine("## Overview (per-vice quantities merged)");
            doc.AppendLine();
            doc.AppendLine("```mermaid");
            doc.AppendLine("flowchart LR");

            var overview = new SortedDictionary<string, EdgeStats>(StringComparer.Ordinal);
            var nodes = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var pair in edges)
            {
                string source = Group(pair.Key.Source);
                string target = Group(pair.Key.Target);
                if (source == target) continue;
                nodes.Add(source);
                nodes.Add(target);
                string key = source + "\u0001" + target;
                if (!overview.TryGetValue(key, out var stats)) overview[key] = stats = new EdgeStats();
                stats.Merge(pair.Value);
            }
            nodes.Add("Curriculum");
            nodes.Add("Suffering");
            foreach (string node in nodes) doc.AppendLine($"  {NodeId(node)}[\"{node}\"]");
            foreach (var pair in overview)
            {
                string[] ends = pair.Key.Split('\u0001');
                doc.AppendLine($"  {NodeId(ends[0])} -->|{pair.Value.Sign}| {NodeId(ends[1])}");
            }
            doc.AppendLine($"  {NodeId("Media")} -.->|cultivation, years| {NodeId("Disposition")}");
            doc.AppendLine($"  {NodeId("Curriculum")} -.->|schooling, a generation| {NodeId("Channels")}");
            doc.AppendLine($"  {NodeId("Contentment")} -.->|below zero| {NodeId("Suffering")}");
            doc.AppendLine("  classDef lever fill:#3A6EA5,stroke:#1B1F24,color:#FFFFFF;");
            doc.AppendLine($"  class {NodeId("Media")},{NodeId("Curriculum")},{NodeId("Law.Severity")} lever;");
            doc.AppendLine("```");

            doc.AppendLine();
            doc.AppendLine("## Every observed term");
            doc.AppendLine();
            doc.AppendLine("Rows marked `*` stand for seven rows, one per vice (Media.Wrath -> Mood.Wrath, and so on).");
            doc.AppendLine("Typical size is the mean absolute contribution per tick across all runs and nations.");
            doc.AppendLine();
            doc.AppendLine("| Source | Target | Sign | Typical size |");
            doc.AppendLine("|---|---|---|---|");

            var detail = new SortedDictionary<string, (string Source, string Target, EdgeStats Stats)>(StringComparer.Ordinal);
            foreach (var pair in edges)
            {
                string source = pair.Key.Source;
                string target = pair.Key.Target;
                string sourceVice = ViceSuffix(source);
                if (sourceVice != null && sourceVice == ViceSuffix(target))
                {
                    source = Prefix(source) + ".*";
                    target = Prefix(target) + ".*";
                }
                string key = target + "\u0001" + source;
                if (!detail.TryGetValue(key, out var row)) detail[key] = row = (source, target, new EdgeStats());
                row.Stats.Merge(pair.Value);
            }
            foreach (var row in detail.Values)
                doc.AppendLine($"| {row.Source} | {row.Target} | {row.Stats.Sign} | {row.Stats.Typical.ToString("0.0000", CultureInfo.InvariantCulture)} |");

            return doc.ToString();
        }

        static string Group(string name)
        {
            string prefix = Prefix(name);
            return prefix != name && PerVicePrefixes.Contains(prefix) ? prefix : name;
        }

        static string Prefix(string name)
        {
            int dot = name.IndexOf('.');
            return dot < 0 ? name : name.Substring(0, dot);
        }

        static string ViceSuffix(string name)
        {
            int dot = name.IndexOf('.');
            if (dot < 0) return null;
            string suffix = name.Substring(dot + 1);
            return Enum.TryParse(suffix, out Vice _) ? suffix : null;
        }

        static string NodeId(string name)
        {
            var id = new StringBuilder("n_");
            foreach (char c in name) id.Append(char.IsLetterOrDigit(c) ? c : '_');
            return id.ToString();
        }
    }
