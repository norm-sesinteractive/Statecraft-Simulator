VERBATIM_DOCS = ("Docs/design/PITCH.md",)  # Norm's own words: exempt from style checks


# ---- small helpers -----------------------------------------------------------------------------

def today() -> str:
    return dt.date.today().isoformat()


def now() -> str:
    return dt.datetime.now().replace(microsecond=0).isoformat()


def rel(path: Path) -> str:
    return path.resolve().relative_to(ROOT).as_posix()


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def write_if_changed(path: Path, content: str) -> bool:
    content = content.replace("\r\n", "\n")
    if path.exists() and read(path).replace("\r\n", "\n") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return True


def banner(command: str) -> str:
    return (f"<!-- GENERATED by Tools/docs/doctool.py {command}. "
            "Do not edit by hand: change the source, then regenerate. -->")


def to_rel(raw: str) -> str | None:
    path = Path(raw)
    if not path.is_absolute():
        path = ROOT / path
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        full, base = os.path.normcase(str(path)), os.path.normcase(str(ROOT))
        if full.startswith(base + os.sep):
            return full[len(base) + 1:].replace("\\", "/")
        return None


def read_hook_input() -> dict:
    try:
        raw = sys.stdin.buffer.read().decode("utf-8")
        return json.loads(raw) if raw.strip() else {}
    except (ValueError, OSError):
        return {}


def load_state() -> dict:
    try:
        state = json.loads(read(STATE_FILE))
    except (OSError, ValueError):
        state = {}
    state.setdefault("pending", {})
    return state


def save_state(state: dict) -> None:
    STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    STATE_FILE.write_text(json.dumps(state, indent=2, sort_keys=True), encoding="utf-8", newline="\n")


def run(args: list[str], timeout: int = 10) -> tuple[int, str]:
    try:
        result = subprocess.run(args, cwd=ROOT, capture_output=True, text=True, timeout=timeout,
                                encoding="utf-8", errors="replace")
        return result.returncode, (result.stdout or "").strip()
    except (OSError, subprocess.TimeoutExpired):
        return 1, ""


# ---- file sets -----------------------------------------------------------------------------------

def hand_written_docs() -> list[Path]:
    docs = []
    for path in sorted(DOCS.rglob("*.md")):
        r = rel(path)
        if r.startswith(("Docs/generated/", "Docs/archive/", "Docs/decisions/")):
            continue
        docs.append(path)
    return docs


def decision_records() -> list[Path]:
    return sorted(p for p in DECISIONS.glob("D-*.md"))


def all_markdown() -> list[Path]:
    files = [CLAUDE_MD, ROOT / "README.md", ROOT / "ArtSource" / "README.md"]
    files += sorted(DOCS.rglob("*.md"))
    files += sorted((ROOT / ".claude" / "skills").rglob("*.md"))
    files += sorted((ROOT / ".claude" / "rules").rglob("*.md"))
    return [f for f in files if f.exists()]


def source_files(*patterns: str) -> list[Path]:
    found = []
    for pattern in patterns:
        for path in ROOT.glob(pattern):
            if path.is_file() and not any(part in ("bin", "obj", "__pycache__") for part in path.parts):
                found.append(path)
    return sorted(set(found))


def authored_files() -> list[Path]:
    files = all_markdown()
    files += source_files("Assets/Scripts/**/*.cs", "Assets/Tests/**/*.cs", "Assets/UI/**/*.uxml",
                          "Assets/UI/**/*.uss", "Tools/**/*.py", "Tools/**/*.ps1", "Tools/**/*.cs",
                          "Tools/**/*.csproj", "Tools/**/*.props", ".claude/settings.json")
    return [f for f in files if rel(f) not in VERBATIM_DOCS]


def ui_files() -> list[Path]:
    return source_files("Assets/Scripts/UI/**/*.cs", "Assets/Scripts/Game/**/*.cs",
                        "Assets/UI/**/*.uxml", "Assets/UI/**/*.uss")


# ---- code map ------------------------------------------------------------------------------------

NAMESPACE_RE = re.compile(r"^\s*namespace\s+([\w.]+)")
TYPE_RE = re.compile(r"^(\s*)(?:\[[^\]]*\]\s*)*((?:public|internal|private|protected)\s+)?"
                     r"((?:static|sealed|abstract|readonly|partial|unsafe|new)\s+)*"
                     r"(class|struct|interface|enum)\s+([A-Za-z_]\w*)")


def first_sentence(doc_lines: list[str]) -> str:
    text = " ".join(doc_lines)
    match = re.search(r"<summary>(.*?)</summary>", text, re.S)
    if not match:
        return ""
    summary = match.group(1)
    summary = re.sub(r'<see\s+cref="(?:[A-Z]:)?([^"(]+)[^"]*"\s*/>', lambda m: m.group(1).split(".")[-1], summary)
    summary = re.sub(r'<(?:paramref|typeparamref)\s+name="([^"]+)"\s*/>', r"\1", summary)
    summary = re.sub(r"<[^>]+>", "", summary)
    summary = re.sub(r"\s+", " ", summary).strip()
    sentence = re.split(r"(?<=[.!?])\s", summary, maxsplit=1)[0]
    return sentence if len(sentence) <= 200 else sentence[:197] + "..."


def scan_cs(path: Path) -> list[tuple[str, str, str, int]]:
    """Returns (name, kind, summary, indent) for every type declared in a C# file."""
    types, doc_lines = [], []
    for line in read(path).splitlines():
        stripped = line.strip()
        if stripped.startswith("///"):
            doc_lines.append(stripped[3:].strip())
            continue
        match = TYPE_RE.match(line)
        if match:
            types.append((match.group(5), match.group(4), first_sentence(doc_lines), len(match.group(1))))
            doc_lines = []
            continue
        if not stripped.startswith("["):
            doc_lines = []
    return types


def assembly_of(path: Path, asmdefs: dict[Path, dict]) -> Path | None:
    for folder in [path.parent, *path.parent.parents]:
        if folder in asmdefs:
            return folder
        if folder == ROOT:
            break
    return None


def codemap_text() -> str:
    asmdefs: dict[Path, dict] = {}
    for asmdef in sorted((ROOT / "Assets").rglob("*.asmdef")):
        try:
            data = json.loads(read(asmdef))
        except ValueError:
            data = {"name": asmdef.stem}
        asmdefs[asmdef.parent] = data

    groups: dict[str, list[str]] = {}
    headers: dict[str, str] = {}
    for folder, data in sorted(asmdefs.items(), key=lambda item: item[1].get("name", "")):
        name = data.get("name", folder.name)
        refs = ", ".join(data.get("references", [])) or "none"
        traits = []
        if data.get("noEngineReferences"):
            traits.append("pure C# (noEngineReferences)")
        if data.get("includePlatforms") == ["Editor"]:
            traits.append("Editor only")
        trait_text = (", " + ", ".join(traits)) if traits else ""
        headers[name] = f"`{rel(folder)}`{trait_text}. References: {refs}."
        groups[name] = []

    runner_dir = ROOT / "Tools" / "Headless" / "Runner"
    headers["Statecraft.SimRunner"] = f"`{rel(runner_dir)}`, headless console tool (not in the game). References: Statecraft.Sim."
    groups["Statecraft.SimRunner"] = []

    for cs in source_files("Assets/**/*.cs", "Tools/Headless/Runner/**/*.cs"):
        if cs.is_relative_to(runner_dir):
            group, base = "Statecraft.SimRunner", runner_dir
        else:
            folder = assembly_of(cs, asmdefs)
            if folder is None:
                group, base = "Assembly-CSharp (no asmdef)", ROOT
                headers.setdefault(group, "Scripts outside any asmdef. Move them into an assembly.")
                groups.setdefault(group, [])
            else:
                group, base = asmdefs[folder].get("name", folder.name), folder
        types = scan_cs(cs)
        path_text = cs.relative_to(base).as_posix()
        top = [t for t in types if t[3] == min((t[3] for t in types), default=0)]
        nested = [t for t in types if t not in top]
        if len(top) == 1 and not nested:
            name, kind, summary, _ = top[0]
            groups[group].append(f"- `{path_text}`: `{name}` ({kind}): {summary or '(no summary)'}")
        else:
            groups[group].append(f"- `{path_text}`" + ("" if types else ": (no types)"))
            for name, kind, summary, indent in types:
                label = "nested " + kind if (name, kind, summary, indent) in nested else kind
                groups[group].append(f"  - `{name}` ({label}): {summary or '(no summary)'}")

    lines = [banner("codemap"), "# Code map", "",
             "Every assembly, source file and type, with the first sentence of each type's XML summary.",
             "Regenerated at session start (SessionStart hook) and by `/wrap-up`. A \"(no summary)\" type needs one.", ""]
    for name in groups:
        lines.append(f"## {name}")
        lines.append("")
        lines.append(headers.get(name, ""))
        lines.append("")
        lines.extend(groups[name] or ["- (no source files yet)"])
        lines.append("")

    lines.append("## Tooling scripts")
    lines.append("")
    for script in source_files("Tools/**/*.ps1", "Tools/**/*.py"):
        lines.append(f"- `{rel(script)}`: {script_synopsis(script)}")
    lines.append("")
    return "\n".join(lines)


def script_synopsis(path: Path) -> str:
    text = read(path)
    if path.suffix == ".ps1":
        match = re.search(r"\.SYNOPSIS\s*\n\s*(.+)", text)
        return match.group(1).strip() if match else "(no .SYNOPSIS)"
    match = re.search(r'^\s*"""(.+?)(?:\n|""")', text, re.S | re.M)
    return match.group(1).strip() if match else "(no docstring)"


def generate_codemap() -> bool:
    return write_if_changed(CODEMAP, codemap_text())


# ---- decisions -----------------------------------------------------------------------------------

def parse_decision(path: Path) -> dict:
    text = read(path)
    title = re.search(r"^#\s+D-(\d{4}):\s*(.+)$", text, re.M)
    status = re.search(r"\*\*Status:\*\*\s*([^|\n]+)", text)
    date = re.search(r"\*\*Date:\*\*\s*([0-9-]+)", text)
    area = re.search(r"\*\*Area:\*\*\s*([^|\n]+)", text)
    return {
        "path": path,
        "id": title.group(1) if title else "",
        "title": title.group(2).strip() if title else "",
        "status": status.group(1).strip() if status else "",
        "date": date.group(1) if date else "",
        "area": area.group(1).strip() if area else "",
        "todo": "TODO" in text,
    }


def decision_index_text() -> str:
    records = [parse_decision(p) for p in decision_records()]
    accepted = sum(1 for r in records if r["status"].startswith("Accepted"))
    proposed = sum(1 for r in records if r["status"].startswith("Proposed"))
    lines = [banner("decisions"), "# Decision index", "",
             f"{len(records)} decisions: {accepted} accepted, {proposed} proposed (Claude's, awaiting Norm).",
             "One small file per decision; create them with `/decide`. Never edit an accepted record: supersede it.", "",
             "| ID | Decision | Status | Date | Area |", "|---|---|---|---|---|"]
    for r in records:
        lines.append(f"| [D-{r['id']}]({r['path'].name}) | {r['title']} | {r['status']} | {r['date']} | {r['area']} |")
    lines.append("")
    return "\n".join(lines)


def generate_decision_index() -> bool:
    return write_if_changed(DECISION_INDEX, decision_index_text())


