#!/usr/bin/env python3
"""Statecraft Simulator documentation tool: hooks, skills and the doc linter call this (stdlib only, Python 3.10+).

Commands (see Docs/architecture/TOOLING.md):
  brief [--refresh]     SessionStart hook: print the session brief (--refresh regenerates codemap and decision index first)
  track                 PostToolUse hook: record code files Claude edits (reads the hook JSON on stdin)
  stop-check            Stop hook: tell Norm when code has moved ahead of the docs (never blocks)
  pending               list code files changed since the last docs sync
  mark-synced           clear that list (the last step of /wrap-up)
  lint [--strict]       budgets, Owns lines, links, map coverage, generated freshness, ASCII UI, em dashes
  codemap               regenerate Docs/generated/CODEMAP.md
  decisions             regenerate Docs/decisions/INDEX.md
  generate [--sim]      codemap and decisions (plus the SimRunner docs with --sim)
  new-decision TITLE    create the next decision record (status Proposed) and print its path
  rotate-worklog        move worklog entries beyond the newest ten into Docs/archive/
"""

