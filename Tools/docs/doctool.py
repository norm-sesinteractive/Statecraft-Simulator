import argparse
import datetime as dt
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "Docs"
GENERATED = DOCS / "generated"
DECISIONS = DOCS / "decisions"
ARCHIVE = DOCS / "archive"
WORKLOG = DOCS / "WORKLOG.md"
CLAUDE_MD = ROOT / "CLAUDE.md"
CODEMAP = GENERATED / "CODEMAP.md"
DECISION_INDEX = DECISIONS / "INDEX.md"
STATE_FILE = ROOT / ".claude" / "state" / "doc-sync.json"
RUNNER = ROOT / "Tools" / "Headless" / "Runner" / "Statecraft.SimRunner.csproj"

CLAUDE_MD_BUDGET = 160
WORKLOG_KEEP = 10
REMIND_AT = (8, 20, 40)
# Built from parts so this file never contains the characters it hunts for.
EM_DASHES = (chr(0x2014), "&" + "mdash;", "&" + "#8212;")

CODE_PREFIXES = ("Assets/Scripts/", "Assets/Tests/", "Assets/UI/", "Tools/", "Packages/manifest.json",
                 "ProjectSettings/", ".claude/settings.json")
