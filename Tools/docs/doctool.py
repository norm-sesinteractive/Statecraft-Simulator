# ---- worklog ---------------------------------------------------------------------------------------

def worklog_parts() -> tuple[str, list[str]]:
    if not WORKLOG.exists():
        return "", []
    parts = re.split(r"(?m)^(?=## )", read(WORKLOG).replace("\r\n", "\n"))
    return parts[0], parts[1:]


# ---- lint ------------------------------------------------------------------------------------------

def lint() -> list[str]:
    warnings: list[str] = []

    for doc in hand_written_docs():
        lines = read(doc).splitlines()
        head = "\n".join(lines[:12])
        if "**Owns:**" not in head:
            warnings.append(f"{rel(doc)}: no '**Owns:**' line in the header")
        budget = re.search(r"\*\*Budget:\*\*\s*(\d+)\s*(lines|entries)", head)
        if not budget:
            warnings.append(f"{rel(doc)}: no '**Budget:** N lines' in the header")
        elif budget.group(2) == "lines" and len(lines) > int(budget.group(1)):
            warnings.append(f"{rel(doc)}: {len(lines)} lines, over its {budget.group(1)}-line budget: split or archive")

    claude_lines = len(read(CLAUDE_MD).splitlines())
    if claude_lines > CLAUDE_MD_BUDGET:
        warnings.append(f"CLAUDE.md: {claude_lines} lines, over its {CLAUDE_MD_BUDGET}-line budget")

    _, entries = worklog_parts()
    if len(entries) > WORKLOG_KEEP:
        warnings.append(f"Docs/WORKLOG.md: {len(entries)} entries, keep {WORKLOG_KEEP}: run doctool rotate-worklog")

    mapped = set(re.findall(r"\]\(([^)#\s]+)", read(CLAUDE_MD)))
    must_map = hand_written_docs() + [CODEMAP, GENERATED / "PARAMETERS.md", GENERATED / "SOCIETY_GRAPH.md", DECISION_INDEX]
    for doc in must_map:
        if rel(doc) not in mapped:
            warnings.append(f"CLAUDE.md: the docs map does not list {rel(doc)}")

    for md in all_markdown():
        text = read(md)
        for target in re.findall(r"\]\(([^)\s]+)\)", text):
            if target.startswith(("http://", "https://", "mailto:", "#")):
                continue
            path_part = re.sub(r":\d+$", "", target.split("#", 1)[0])
            if path_part and not (md.parent / path_part).exists():
                warnings.append(f"{rel(md)}: broken link '{target}'")

    for name in ("PARAMETERS.md", "SOCIETY_GRAPH.md"):
        if not (GENERATED / name).exists():
            warnings.append(f"Docs/generated/{name} is missing: run doctool generate --sim")
    if not CODEMAP.exists() or read(CODEMAP).replace("\r\n", "\n") != codemap_text():
        warnings.append("Docs/generated/CODEMAP.md is stale: run doctool codemap")
    if not DECISION_INDEX.exists() or read(DECISION_INDEX).replace("\r\n", "\n") != decision_index_text():
        warnings.append("Docs/decisions/INDEX.md is stale: run doctool decisions")
    for generated in sorted(GENERATED.glob("*.md")):
        if not read(generated).startswith("<!-- GENERATED"):
            warnings.append(f"{rel(generated)}: missing the GENERATED banner (hand-written file in Docs/generated?)")

    for record in decision_records():
        info = parse_decision(record)
        expected = record.name[2:6]
        if not info["id"]:
            warnings.append(f"{rel(record)}: first line must be '# D-NNNN: Title'")
        elif info["id"] != expected:
            warnings.append(f"{rel(record)}: heading says D-{info['id']}, file name says D-{expected}")
        if not info["status"]:
            warnings.append(f"{rel(record)}: no '**Status:**' line")
        if info["todo"]:
            warnings.append(f"{rel(record)}: still contains TODO")

    for path in authored_files():
        for number, line in enumerate(read(path).splitlines(), 1):
            if any(dash in line for dash in EM_DASHES):
                warnings.append(f"{rel(path)}:{number}: em dash (CLAUDE.md rule 10)")

    for path in ui_files():
        for number, line in enumerate(read(path).splitlines(), 1):
            if any(ord(ch) > 127 for ch in line):
                warnings.append(f"{rel(path)}:{number}: non-ASCII character in UI source (renders as a box on device fonts)")

    return warnings


# ---- commands --------------------------------------------------------------------------------------

def cmd_brief(args: argparse.Namespace) -> int:
    notes = []
    if args.refresh:
        try:
            changed = [name for name, did in (("CODEMAP", generate_codemap()), ("decision index", generate_decision_index())) if did]
            if changed:
                notes.append("regenerated " + " and ".join(changed))
        except Exception as error:  # the brief must never fail the session start
            notes.append(f"refresh failed: {error}")

    lines = ["## Session brief (Tools/docs/doctool.py brief)", f"- Date: {today()}." + (f" ({'; '.join(notes)})" if notes else "")]
    lines.append(git_line())
    lines.append(editor_line())
    lines.append(drift_line())
    try:
        warnings = lint()
    except Exception as error:
        warnings = [f"lint crashed: {error}"]
    lint_text = f"- Doc lint: {len(warnings)} warning(s)."
    if warnings:
        lint_text += " First: " + "; ".join(warnings[:4]) + (". Run `python Tools/docs/doctool.py lint`." if len(warnings) > 4 else ".")
    lines.append(lint_text)
    _, entries = worklog_parts()
    if entries:
        lines.append(f"- Last worklog entry: {entries[0].splitlines()[0][3:].strip()}.")
    lines.append("- Docs/STATUS.md is loaded through CLAUDE.md. Fuller orientation: /catch-up. End sessions with /wrap-up.")
    print("\n".join(lines))
    return 0


def git_line() -> str:
    if not (ROOT / ".git").exists():
        return "- Git: no repository yet. Norm runs every git write (D-0003); hand over the commands."
    _, branch = run(["git", "branch", "--show-current"])
    _, status = run(["git", "status", "--porcelain"])
    changed = len([line for line in status.splitlines() if line.strip()])
    code, last = run(["git", "log", "-1", "--format=%cs %s"])
    return f"- Git: branch {branch or '?'}, {changed} uncommitted change(s). Last commit: {last if code == 0 and last else 'none yet'}."


def editor_line() -> str:
    if not (ROOT / "Temp" / "UnityLockfile").exists():
        return "- Unity: no editor holds this project; batch runs (Tools/unity.ps1) are possible."
    code, output = run(["powershell", "-NoProfile", "-NonInteractive", "-Command",
                        "Get-CimInstance Win32_Process -Filter \"Name='Unity.exe'\" | ForEach-Object { $_.CommandLine }"], timeout=20)
    if code != 0:
        return "- Unity: Temp/UnityLockfile exists, so the editor is probably open. Use the headless harness."
    root = str(ROOT).lower()
    holders = [line for line in output.splitlines() if root in line.replace("/", "\\").lower()]
    if not holders:
        return "- Unity: stale Temp/UnityLockfile, no editor running; batch runs are possible."
    if all("-batchmode" in line.lower() for line in holders):
        return "- Unity: a batch run is in progress for this project."
    return ("- Unity: the EDITOR IS OPEN on this project. Batch runs will fail; use the headless harness "
            "and tell Norm what to check in the editor.")


def drift_line() -> str:
    state = load_state()
    pending = sorted(state.get("pending", {}))
    last = state.get("last_sync") or "never"
    if not pending:
        return f"- Docs drift: none since the last sync ({last})."
    shown = ", ".join(pending[:6]) + (f" and {len(pending) - 6} more" if len(pending) > 6 else "")
    return f"- Docs drift: {len(pending)} code file(s) changed since the last sync ({last}): {shown}. Check their owning docs."


def emit_context(event: str, message: str) -> None:
    print(json.dumps({"hookSpecificOutput": {"hookEventName": event, "additionalContext": message}}))


def cmd_track(args: argparse.Namespace) -> int:
    data = read_hook_input()
    tool_input = data.get("tool_input") or {}
    raw = tool_input.get("file_path") or tool_input.get("notebook_path")
    path = to_rel(raw) if raw else None
    if not path:
        return 0
    if path.startswith(GENERATED_PATHS):
        emit_context("PostToolUse", f"{path} is generated; hand edits are overwritten. Change the source, then run "
                                    "`python Tools/docs/doctool.py generate --sim`.")
        return 0
    if not path.startswith(CODE_PREFIXES):
        return 0
    state = load_state()
    pending = state["pending"]
    if path not in pending:
        pending[path] = now()
        count = len(pending)
        if count in REMIND_AT and state.get("reminded_at", 0) < count:
            state["reminded_at"] = count
            emit_context("PostToolUse", f"Docs drift: {count} code files changed since the last docs sync "
                                        f"({state.get('last_sync') or 'never'}). Keep owning docs current as you go, "
                                        "or run /wrap-up at a natural stopping point.")
        save_state(state)
    return 0


def cmd_stop_check(args: argparse.Namespace) -> int:
    data = read_hook_input()
    if data.get("stop_hook_active"):
        return 0
    state = load_state()
    count = len(state["pending"])
    if count == 0 or state.get("notified_count") == count:
        return 0
    state["notified_count"] = count
    save_state(state)
    print(json.dumps({"systemMessage": f"Docs drift: {count} code file(s) changed since the last /wrap-up. "
                                       "Ask Claude to /wrap-up before ending the session."}))
    return 0


def cmd_pending(args: argparse.Namespace) -> int:
    state = load_state()
    pending = state["pending"]
    print(f"Last docs sync: {state.get('last_sync') or 'never'}. Code files changed since: {len(pending)}.")
    for path in sorted(pending):
        print(f"  {path}  (first edited {pending[path]})")
    return 0


def cmd_mark_synced(args: argparse.Namespace) -> int:
    save_state({"pending": {}, "last_sync": today(), "reminded_at": 0, "notified_count": 0})
    print(f"Docs marked in sync as of {today()}.")
    return 0


def cmd_lint(args: argparse.Namespace) -> int:
    warnings = lint()
    for warning in warnings:
        print(f"WARN {warning}")
    print(f"Doc lint: {len(warnings)} warning(s).")
    return 1 if (args.strict and warnings) else 0


def cmd_codemap(args: argparse.Namespace) -> int:
    print("CODEMAP.md " + ("regenerated." if generate_codemap() else "already current."))
    return 0


def cmd_decisions(args: argparse.Namespace) -> int:
    print("Decision index " + ("regenerated." if generate_decision_index() else "already current."))
    return 0


def cmd_generate(args: argparse.Namespace) -> int:
    done = []
    if generate_codemap():
        done.append("CODEMAP.md")
    if generate_decision_index():
        done.append("decisions/INDEX.md")
    if args.sim:
        code, output = run(["dotnet", "run", "--project", str(RUNNER), "--", "docs", "--out", str(GENERATED)], timeout=600)
        if code != 0:
            print(output[-3000:])
            print("SimRunner docs failed (see above).")
            return 1
        done.append("PARAMETERS.md and SOCIETY_GRAPH.md (from SimRunner)")
    print("Regenerated: " + (", ".join(done) if done else "nothing; all current."))
    return 0


def cmd_new_decision(args: argparse.Namespace) -> int:
    title = " ".join(args.title).strip()
    if not title:
        print("Give a title: new-decision \"Short imperative title\"")
        return 2
    numbers = [int(m.group(1)) for p in decision_records() if (m := re.match(r"D-(\d{4})-", p.name))]
    number = max(numbers, default=0) + 1
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:50].rstrip("-") or "decision"
    path = DECISIONS / f"D-{number:04d}-{slug}.md"
    path.write_text(DECISION_TEMPLATE.format(number=number, title=title, date=today()), encoding="utf-8", newline="\n")
    generate_decision_index()
    print(rel(path))
    return 0


def cmd_rotate_worklog(args: argparse.Namespace) -> int:
    header, entries = worklog_parts()
    if len(entries) <= WORKLOG_KEEP:
        print(f"Worklog has {len(entries)} entries; nothing to rotate.")
        return 0
    keep, old = entries[:WORKLOG_KEEP], entries[WORKLOG_KEEP:]
    archive = ARCHIVE / "WORKLOG-archive.md"
    archive_header = "# Worklog archive\n\nOlder worklog entries, newest first. Grep it; do not read it whole.\n\n"
    archived = read(archive).replace("\r\n", "\n") if archive.exists() else archive_header
    if not archived.startswith(archive_header):
        archived = archive_header + archived
    archived = archive_header + "".join(old) + archived[len(archive_header):]
    write_if_changed(archive, archived)
    write_if_changed(WORKLOG, header + "".join(keep))
    print(f"Moved {len(old)} entries to {rel(archive)}.")
    return 0


